const csvEsc = (s) => (/[;"\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
const csv =
  "﻿" +
  ["Запрос;Тип;Кластер;Целевая страница;Приоритет;Частота Wordstat (точная, Чебоксары)"]
    .concat(rows.map((r) => [r.q, r.intent, r.cluster, r.url, r.prio, ""].map(csvEsc).join(";")))
