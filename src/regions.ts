export const applySeo = (t: { title: string; description: string; keywords: string }) => {
  document.title = t.title;
  const set = (attr: string, key: string, value: string) => {
    let el = document.head.querySelector(`meta[${attr}="${key}"]`) as HTMLMetaElement | null;
    if (!el) {
      el = document.createElement("meta");
      el.setAttribute(attr, key);
      document.head.appendChild(el);
    }
    el.setAttribute("content", value);
  };
  set("name", "description", t.description);
  set("name", "keywords", t.keywords);
  set("property", "og:title", t.title);
  set("property", "og:description", t.description);
};

